-- Sites are setup metadata only; student registration behavior is unchanged.
ALTER TABLE events ADD COLUMN starts_at TIMESTAMP;
ALTER TABLE events ADD COLUMN ends_at TIMESTAMP;
CREATE TABLE event_sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    location VARCHAR(1000) NOT NULL,
    description VARCHAR(5000),
    requirements VARCHAR(5000),
    registration_url VARCHAR(2000),
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    starts_at TIMESTAMP,
    ends_at TIMESTAMP
);
CREATE INDEX event_sites_event_order ON event_sites(event_id, display_order);
